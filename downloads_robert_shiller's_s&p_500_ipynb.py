import matplotlib.pyplot as plt
import pandas as pd

def plot_classic_series(df):
    """
    Plots the Shiller dataset time series in a single figure with a classic aesthetic.
    Features serif fonts, traditional colors, and a stacked subplot layout.
    """
    # Configure classic aesthetic parameters (academic/traditional financial look)
    plt.rcParams.update({
        'font.family': 'serif',
        'axes.labelsize': 10,
        'axes.titlesize': 12,
        'xtick.labelsize': 9,
        'ytick.labelsize': 9,
        'axes.grid': True,
        'grid.linestyle': ':',
        'grid.alpha': 0.6
    })

    # Create a figure with 3 stacked subplots sharing the X-axis
    fig, axes = plt.subplots(3, 1, figsize=(10, 8), sharex=True)
    fig.suptitle('S&P 500 Historical Market Data', fontsize=14, fontweight='bold', y=0.95)

    # 1. Real Price
    axes[0].plot(df['Date'], df['Price'], color='navy', linewidth=1.2)
    axes[0].set_title('Real Price (Inflation Adjusted)')
    axes[0].set_ylabel('Index Value')

    # 2. Real Dividends
    axes[1].plot(df['Date'], df['Dividend'], color='darkgreen', linewidth=1.2)
    axes[1].set_title('Real Dividends')
    axes[1].set_ylabel('Dividends')

    # 3. Interest Rate
    axes[2].plot(df['Date'], df['Interest_Rate'], color='darkred', linewidth=1.2)
    axes[2].set_title('Long-Term Interest Rate (10-Year)')
    axes[2].set_ylabel('Rate (%)')
    axes[2].set_xlabel('Year')

    # Adjust layout to prevent overlap
    plt.tight_layout()
    plt.subplots_adjust(top=0.88) # Leave space for the main title

    plt.show()

