import pandas as pd
import numpy as np

def load_shiller_data(url="http://www.econ.yale.edu/~shiller/data/ie_data.xls"):
    """
    Downloads and processes Robert Shiller's S&P 500 dataset directly from Yale's servers.
    Extracts nominal prices, nominal dividends, and CPI, and returns a deflated DataFrame.
    """
    print(f"Downloading data directly from Robert Shiller's website...")
    print(f"URL: {url}")

    # 1. Read the Excel file skipping the first 7 metadata rows
    try:
        df_raw = pd.read_excel(url, sheet_name='Data', skiprows=7)
    except Exception as e:
        raise ConnectionError(f"Failed to download or read the Excel file. Error: {e}")

    # 2. Drop rows where the Date column is NaN (Shiller leaves notes at the very bottom)
    df_raw = df_raw.dropna(subset=[df_raw.columns[0]])

    # 3. Extract columns by index to avoid header naming mismatches
    # Index 0: Date (YYYY.MM)
    # Index 1: Nominal Price (P)
    # Index 2: Nominal Dividend (D)
    # Index 4: CPI (Consumer Price Index)
    # Index 6: Long Interest Rate (GS10) -> Taxa de Juros
    df = df_raw.iloc[:, [0, 1, 2, 4, 6]].copy()
    df.columns = ['RawDate', 'Nominal_Price', 'Nominal_Dividend', 'CPI', 'Interest_Rate']

    # 4. Parse Shiller's unique fractional Date format robustly
    # We format as string with 2 decimal places to ensure .10 (Oct) doesn't become .1 (Jan)
    df['RawDate_str'] = df['RawDate'].apply(lambda x: f"{x:.2f}")

    # Split into Year and Month
    df['Year'] = df['RawDate_str'].str.split('.').str[0].astype(int)
    df['Month'] = df['RawDate_str'].str.split('.').str[1].astype(int)

    # Create proper Pandas Datetime
    df['Date'] = pd.to_datetime(df.assign(Day=1)[['Year', 'Month', 'Day']])

    # 5. Clean rows with missing financial data (including missing interest rates)
    df = df.dropna(subset=['Nominal_Price', 'Nominal_Dividend', 'CPI', 'Interest_Rate'])

    # 6. Deflate Nominal Values to Real Values (Inflation Adjusted)
    # Anchor to the most recent CPI available in the dataset
    latest_cpi = df['CPI'].iloc[-1]

    df['Price'] = df['Nominal_Price'] * (latest_cpi / df['CPI'])
    df['Dividend'] = df['Nominal_Dividend'] * (latest_cpi / df['CPI'])

    # 7. Final formatting matching the expected GMM input
    df_final = df[['Date', 'Price', 'Dividend', 'Interest_Rate']].copy()
    df_final = df_final.sort_values('Date').reset_index(drop=True)

    print(f"Successfully loaded {len(df_final)} months of data from {df_final['Date'].min().strftime('%Y-%m')} to {df_final['Date'].max().strftime('%Y-%m')}.")

    return df_final

